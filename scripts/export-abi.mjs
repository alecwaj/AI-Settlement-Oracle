// Copies the compiled SettlementOracle ABI into the oracle and demo packages.
// Run after `forge build`: node scripts/export-abi.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const artifact = JSON.parse(
  readFileSync(path.join(root, 'contracts/out/SettlementOracle.sol/SettlementOracle.json'), 'utf8'),
);
const body = `// AUTO-GENERATED by scripts/export-abi.mjs from contracts/out. Do not edit.\nexport const settlementOracleAbi = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`;
for (const target of ['oracle/src/abi.ts', 'demo/src/abi.ts']) {
  writeFileSync(path.join(root, target), body);
  console.log('wrote', target);
}
